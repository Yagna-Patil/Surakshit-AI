package com.example.myapplication

enum class RiskLevel {
    SAFE,
    SUSPICIOUS,
    DANGEROUS
}

enum class FraudType {
    SMS,
    URL,
    CALL,
    QR_CODE
}

data class AnalysisResult(
    val headline: String,
    val explanation: String,
    val advice: String,
    val voiceAlert: String,
    val riskLevel: RiskLevel,
    val type: FraudType = FraudType.SMS
)

object ScamAnalyzer {

    fun analyze(message: String, languageCode: String, type: FraudType = FraudType.SMS): AnalysisResult {
        val lowerMessage = message.lowercase().trim()
        val lang = sanitizeLangCode(languageCode)

        // 1. Fake QR Code / UPI Money Request Scam Detection
        val isQrScam = lowerMessage.contains("upi://pay") ||
                (lowerMessage.contains("pa=") && lowerMessage.contains("am=")) ||
                (type == FraudType.QR_CODE && (lowerMessage.contains("pay") || lowerMessage.contains("upi") || lowerMessage.contains("pin") || lowerMessage.contains("collect")))

        // 2. Malicious URL Detection
        val hasUrl = UrlAnalyzer.containsUrl(message)
        val isUrlScam = (hasUrl && UrlAnalyzer.isDangerousUrl(message)) || type == FraudType.URL

        // 3. Digital Arrest Scam
        val isDigitalArrest = CallAnalyzer.isDigitalArrestCall(message)

        // 4. Electricity Disconnection Scam
        val isElectricityScam = CallAnalyzer.isElectricityCall(message) ||
                ((lowerMessage.contains("electricity") || lowerMessage.contains("power") || lowerMessage.contains("bijli")) &&
                        (lowerMessage.contains("disconnect") || lowerMessage.contains("tonight") || lowerMessage.contains("officer")))

        // 5. Fake UPI Money Request
        val isUpiFraud = (lowerMessage.contains("paytm") || lowerMessage.contains("phonepe") || lowerMessage.contains("gpay") || lowerMessage.contains("upi")) &&
                (lowerMessage.contains("credited") || lowerMessage.contains("request") || lowerMessage.contains("pin to receive") || lowerMessage.contains("collect"))

        // 6. Dangerous Keywords
        val isGeneralDangerous = listOf("otp", "account blocked", "suspended", "urgent action required", "verify immediately", "lottery", "claim reward", "install app", "apk")
            .any { lowerMessage.contains(it) }

        // 7. Suspicious Keywords
        val isSuspicious = listOf("click link", "discount", "free offer", "limited time", "update kyc", "loan approved")
            .any { lowerMessage.contains(it) }

        return when {
            isQrScam -> AnalysisResult(
                headline = getTranslation("headline_qr", lang),
                explanation = getTranslation("explanation_qr", lang),
                advice = getTranslation("advice_qr", lang),
                voiceAlert = getTranslation("voice_qr", lang),
                riskLevel = RiskLevel.DANGEROUS,
                type = FraudType.QR_CODE
            )

            isUrlScam -> AnalysisResult(
                headline = getTranslation("headline_url", lang),
                explanation = getTranslation("explanation_url", lang),
                advice = getTranslation("advice_url", lang),
                voiceAlert = getTranslation("voice_url", lang),
                riskLevel = RiskLevel.DANGEROUS,
                type = FraudType.URL
            )

            isDigitalArrest -> AnalysisResult(
                headline = getTranslation("headline_digital_arrest", lang),
                explanation = getTranslation("explanation_digital_arrest", lang),
                advice = getTranslation("advice_digital_arrest", lang),
                voiceAlert = getTranslation("voice_digital_arrest", lang),
                riskLevel = RiskLevel.DANGEROUS,
                type = type
            )

            isElectricityScam -> AnalysisResult(
                headline = getTranslation("headline_electricity", lang),
                explanation = getTranslation("explanation_electricity", lang),
                advice = getTranslation("advice_electricity", lang),
                voiceAlert = getTranslation("voice_electricity", lang),
                riskLevel = RiskLevel.DANGEROUS,
                type = type
            )

            isUpiFraud -> AnalysisResult(
                headline = getTranslation("headline_upi", lang),
                explanation = getTranslation("explanation_upi", lang),
                advice = getTranslation("advice_upi", lang),
                voiceAlert = getTranslation("voice_upi", lang),
                riskLevel = RiskLevel.DANGEROUS,
                type = type
            )

            isGeneralDangerous -> AnalysisResult(
                headline = getTranslation("headline_dangerous", lang),
                explanation = getTranslation("explanation_dangerous", lang),
                advice = getTranslation("advice_dangerous", lang),
                voiceAlert = getTranslation("voice_dangerous", lang),
                riskLevel = RiskLevel.DANGEROUS,
                type = type
            )

            isSuspicious -> AnalysisResult(
                headline = getTranslation("headline_suspicious", lang),
                explanation = getTranslation("explanation_suspicious", lang),
                advice = getTranslation("advice_suspicious", lang),
                voiceAlert = getTranslation("voice_suspicious", lang),
                riskLevel = RiskLevel.SUSPICIOUS,
                type = type
            )

            else -> AnalysisResult(
                headline = getTranslation("headline_safe", lang),
                explanation = getTranslation("explanation_safe", lang),
                advice = getTranslation("advice_safe", lang),
                voiceAlert = getTranslation("voice_safe", lang),
                riskLevel = RiskLevel.SAFE,
                type = type
            )
        }
    }

